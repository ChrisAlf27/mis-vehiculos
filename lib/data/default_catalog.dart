/// Los tipos de vehículo y mantenimientos "de fábrica". Sólo se usan para
/// sembrar la base la primera vez: después, todo es editable desde la app.
class DefaultVehicleType {
  final String key;
  final String nameEs;
  final String nameEn;
  final String icon;

  const DefaultVehicleType({
    required this.key,
    required this.nameEs,
    required this.nameEn,
    required this.icon,
  });

  String getName(String locale) => locale.startsWith('en') ? nameEn : nameEs;
}

class DefaultMaintenanceType {
  final String id;
  final String nameEs;
  final String nameEn;
  final String vehicleKey;
  final int intervalKm;
  final int intervalDays;
  final String priority;
  final String descriptionEs;
  final String descriptionEn;
  final String icon;

  const DefaultMaintenanceType({
    required this.id,
    required this.nameEs,
    required this.nameEn,
    required this.vehicleKey,
    required this.intervalKm,
    required this.intervalDays,
    required this.priority,
    required this.descriptionEs,
    required this.descriptionEn,
    required this.icon,
  });

  String getName(String locale) => locale.startsWith('en') ? nameEn : nameEs;
  String getDescription(String locale) =>
      locale.startsWith('en') ? descriptionEn : descriptionEs;
}

